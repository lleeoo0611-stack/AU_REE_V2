stopifnot(max(abs(topsis(X,w)-c(1,0,.5)))<1e-9)
stopifnot(abs(ahp(outer(c(.6,.3,.1),c(.6,.3,.1),'/'))$CR)<1e-8)
bad<-matrix(c(1,9,1/9,1/9,1,9,9,1/9,1),3)
stopifnot(inherits(try(ahp(bad),silent=TRUE),'try-error'))
tie<-matrix(.5,3,2)
