"""Restore the exact run contract for a read-only export of an integrated database."""
import json
from pathlib import PurePosixPath

from .acquisition import checked_replay_path
from .eligibility import HISTORICAL_C1_CONFIG_FILES, c1_cohort_disabled
from .store import digest, filehash
from .tabular import read_csv


# Identifies integrated stores even if copied outside their original directory tree.
INTEGRATED_APPLICATION_ID = int.from_bytes(b'AURE', 'big')


def export_contract_hashes(root, configuration):
    hashes = {name: filehash(root/'config'/name) for name in
              ('summary_rules.json', 'researcher_rule_decisions.json', 'project_summary_columns.json')}
    evidence_files = ['config/assay_evidence.json', 'config/candidate_milestones.json',
                      'data/candidate_milestone_evidence.json']
    if not c1_cohort_disabled(configuration.get('research', {})):
        evidence_files.extend('config/'+name for name in sorted(HISTORICAL_C1_CONFIG_FILES))
    hashes.update({file: filehash(root/file) for file in evidence_files if (root/file).is_file()})
    return hashes


def resolve_export_assets(root, snapshots, run_dir, replay_assets):
    """Rebind generated pages to this run; never open an undeclared external path."""
    resolved = {}
    for source in snapshots:
        for entry in (source, *source.get('original_responses', [])):
            path = entry['path']
            parts = PurePosixPath(path.replace('\\', '/')).parts
            anchor = root
            if len(parts) >= 4 and parts[-4:-1] == ('runs', run_dir.name, 'verified-pages'):
                anchor = run_dir
                path = 'verified-pages/' + parts[-1]
            cache_key = (anchor, path, entry['sha256'])
            if cache_key not in resolved:
                verified = checked_replay_path(anchor, dict(entry, path=path), source['key'],
                    replay_assets=replay_assets, receipt_paths=True)
                resolved[cache_key] = str(verified.resolve())
            entry['path'] = resolved[cache_key]


def read_run_inputs(db, database, root, run, cutoff, replay_assets):
    run_id = run['run_id']
    if not run_id or run_id in ('.', '..') or any(ch in run_id for ch in ('/', '\\', ':')):
        raise ValueError('SUMMARY_RUN_METADATA_REQUIRED: invalid run ID')
    integrated_layout = database.parent.parent.name == 'databases'
    if integrated_layout and database.parent.name != run_id:
        raise ValueError('SUMMARY_RUN_METADATA_REQUIRED: database/run ID mismatch')
    work = database.parents[2] if integrated_layout else database.parent
    run_dir = work/'runs'/run_id
    tagged = db.execute('PRAGMA application_id').fetchone()[0] == INTEGRATED_APPLICATION_ID
    if not run_dir.is_dir() and not (integrated_layout or tagged or replay_assets is not None):
        # Older releases predate the header marker. A verified-pages source
        # generated by this exact run also identifies an integrated build after
        # its database has been copied on its own and arbitrarily renamed.
        legacy_pages = db.execute("""SELECT path FROM sources
            WHERE kind='pdf_page_extraction' AND instr(path,'verified-pages') > 0""")
        evidenced = any(PurePosixPath(row[0].replace('\\','/')).parts[-4:-1]
                        == ('runs',run_id,'verified-pages') for row in legacy_pages)
        if not evidenced:
            return None
    configuration_file = run_dir/'configuration.json'
    if not configuration_file.is_file():
        raise ValueError('SUMMARY_RUN_METADATA_REQUIRED: configuration.json')
    config = json.loads(configuration_file.read_text(encoding='utf8'))
    if digest(config) != run['config_sha']:
        raise ValueError('SUMMARY_RUN_CONFIGURATION_HASH_MISMATCH')
    integrated = integrated_layout or tagged or bool(config.get('source_mode')) or replay_assets is not None
    lock = run_dir/'snapshot_lock.json'
    if not lock.is_file():
        raise ValueError('SUMMARY_RUN_SNAPSHOT_REQUIRED')
    snapshots = json.loads(lock.read_text(encoding='utf8'))
    if digest(snapshots) != run['snapshot_sha']:
        raise ValueError('SUMMARY_RUN_SNAPSHOT_HASH_MISMATCH')
    if not integrated:
        resolve_export_assets(root, snapshots, run_dir, replay_assets)
        return config, snapshots, None, None
    summary_file = run_dir/'summary.json'
    if config.get('source_mode') not in ('offline','live','frozen') or not summary_file.is_file():
        raise ValueError('SUMMARY_RUN_METADATA_REQUIRED: source_mode or summary.json')
    summary = json.loads(summary_file.read_text(encoding='utf8'))
    if (summary.get('run_id') != run_id or summary.get('status') != 'COMPLETED'
            or summary.get('cutoff') != run['cutoff'] or cutoff != run['cutoff']
            or summary.get('configuration_sha256') != run['config_sha']
            or summary.get('snapshot_sha256') != run['snapshot_sha']):
        raise ValueError('SUMMARY_RUN_METADATA_REQUIRED: run/configuration/snapshot mismatch')
    saved = summary.get('project_summary',{}).get('export_contract_sha256',{})
    hashes = export_contract_hashes(root, config)
    base = {'summary_rules.json','researcher_rule_decisions.json','project_summary_columns.json'}
    if (not base.issubset(saved) or (tagged and set(saved) != set(hashes))
            or any(hashes.get(name) != sha for name,sha in saved.items())):
        raise ValueError('SUMMARY_EXPORT_CONTRACT_CHANGED')
    outputs = summary.get('output_hashes', {})
    def report(filename, error):
        path = run_dir/filename
        if not path.is_file() or filehash(path) != outputs.get(filename):
            raise ValueError(error)
        return read_csv(path)
    members = report('canonical_membership.csv','SUMMARY_RUN_MEMBERSHIP_INVALID')
    # Frozen mode reads an immutable snapshot and performs no acquisition.
    outcomes = (report('acquisition_report.csv','SUMMARY_RUN_ACQUISITION_INVALID')
                if config['source_mode'] != 'frozen' else [])
    resolve_export_assets(root, snapshots, run_dir, replay_assets)
    return config, snapshots, members, outcomes
